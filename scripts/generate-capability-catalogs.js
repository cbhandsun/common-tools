#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const { CAPABILITY_MANIFESTS } = require("../packages/capability-manifests");

function assertSourceEntries(entries, label) {
  if (!Array.isArray(entries)) throw new TypeError(`${label} is invalid`);
  for (const key of ["capability", "packageName", "requirePath"]) {
    const seen = new Set();
    for (const entry of entries) {
      if (seen.has(entry[key])) throw new TypeError(`${label} contains duplicate ${key}: ${entry[key]}`);
      seen.add(entry[key]);
    }
  }
  return Object.freeze(entries);
}

function assertExpectedExportName(entry, expectedExportName, label) {
  if (entry.exportName !== expectedExportName) throw new TypeError(`${label} must export ${expectedExportName}: ${entry.capability}`);
}

function compareAscii(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function sourceCatalogFromManifests(manifests = CAPABILITY_MANIFESTS) {
  if (!(manifests instanceof Map)) throw new TypeError("capability manifests are invalid");
  const local = [];
  const direct = [];
  for (const manifest of [...manifests.values()].sort((left, right) => compareAscii(left.capability, right.capability))) {
    const entry = Object.freeze({ capability: manifest.capability, ...manifest.moduleSource });
    if (manifest.requiredWorkerProfile === "direct") {
      assertExpectedExportName(entry, "REMOTE_CAPABILITY_MODULE", "direct capability module source");
      direct.push(entry);
    } else {
      assertExpectedExportName(entry, "CAPABILITY_MODULE", "local capability module source");
      local.push(entry);
    }
  }
  return Object.freeze({
    version: 1,
    local: assertSourceEntries(local, "local capability module sources"),
    direct: assertSourceEntries(direct, "direct capability module sources")
  });
}

function variableNameFor(entry) {
  return `${entry.capability.replaceAll("-", "_").toUpperCase()}_${entry.exportName}`;
}

function renderLocalCatalog(sources) {
  const imports = sources.map((entry) => `const { ${entry.exportName}: ${variableNameFor(entry)} } = require("${entry.requirePath}");`).join("\n");
  const records = sources.map((entry) => `  Object.freeze({ packageName: "${entry.packageName}", module: ${variableNameFor(entry)} })`).join(",\n");
  return `"use strict";

// Generated by scripts/generate-capability-catalogs.js. Do not edit by hand.
${imports}

const LOCAL_CAPABILITY_CATALOG = Object.freeze([
${records}
]);

function loadLocalCapabilityModules() {
  return Object.freeze(LOCAL_CAPABILITY_CATALOG.map((entry) => entry.module));
}

module.exports = {
  LOCAL_CAPABILITY_CATALOG,
  loadLocalCapabilityModules
};
`;
}

function renderDirectCatalog(sources) {
  const imports = sources.map((entry) => `const { ${entry.exportName}: ${variableNameFor(entry)} } = require("${entry.requirePath}");`).join("\n");
  const records = sources.map((entry) => `  Object.freeze({ packageName: "${entry.packageName}", module: ${variableNameFor(entry)} })`).join(",\n");
  return `"use strict";

// Generated by scripts/generate-capability-catalogs.js. Do not edit by hand.
${imports}

const DIRECT_CAPABILITY_SOURCE_CATALOG = Object.freeze([
${records}
]);
const DIRECT_CAPABILITY_CATALOG = Object.freeze(DIRECT_CAPABILITY_SOURCE_CATALOG.map((entry) => entry.module));

function directCapabilityModules() {
  return Object.freeze([...DIRECT_CAPABILITY_CATALOG]);
}

function mergeDirectToolMap(label, pick) {
  const merged = {};
  for (const module of DIRECT_CAPABILITY_CATALOG) {
    const entries = pick(module);
    if (!entries || typeof entries !== "object" || Array.isArray(entries)) throw new Error(\`direct capability \${label} map is invalid\`);
    for (const [name, value] of Object.entries(entries)) {
      if (Object.prototype.hasOwnProperty.call(merged, name)) throw new Error(\`duplicate direct capability \${label}: \${name}\`);
      merged[name] = value;
    }
  }
  return Object.freeze(merged);
}

function directToolContracts() {
  const seen = new Set();
  const contracts = [];
  for (const module of DIRECT_CAPABILITY_CATALOG) {
    const tools = module.directToolContracts || [];
    if (!Array.isArray(tools)) throw new Error("direct capability tool contracts are invalid");
    for (const tool of tools) {
      if (!tool || typeof tool !== "object" || typeof tool.name !== "string") throw new Error("direct capability tool contract is invalid");
      if (seen.has(tool.name)) throw new Error(\`duplicate direct capability contract: \${tool.name}\`);
      seen.add(tool.name);
      contracts.push(tool);
    }
  }
  return Object.freeze(contracts);
}

function directToolArguments() {
  return mergeDirectToolMap("argument", (module) => module.directToolArguments || {});
}

function directToolMethods() {
  return mergeDirectToolMap("method", (module) => module.directToolMethods || {});
}

module.exports = {
  DIRECT_CAPABILITY_CATALOG,
  DIRECT_CAPABILITY_SOURCE_CATALOG,
  directCapabilityModules,
  directToolArguments,
  directToolContracts,
  directToolMethods,
  mergeDirectToolMap
};
`;
}

function generatedCatalogFiles(catalog = sourceCatalogFromManifests()) {
  return Object.freeze([
    Object.freeze({
      path: path.join(root, "packages", "capability-registry", "local-capability-catalog.js"),
      content: renderLocalCatalog(catalog.local)
    }),
    Object.freeze({
      path: path.join(root, "packages", "remote-mcp-server", "direct-capability-catalog.js"),
      content: renderDirectCatalog(catalog.direct)
    })
  ]);
}

function writeGeneratedCatalogs() {
  for (const file of generatedCatalogFiles()) fs.writeFileSync(file.path, file.content);
}

function firstDifference(left, right) {
  const max = Math.min(left.length, right.length);
  for (let index = 0; index < max; index += 1) if (left[index] !== right[index]) return index;
  return left.length === right.length ? -1 : max;
}

function summarizeDifference(actual, expected) {
  const index = firstDifference(actual, expected);
  const windowStart = Math.max(0, index - 40);
  const windowEnd = index < 0 ? 0 : index + 80;
  return Object.freeze({
    actualLength: actual.length,
    expectedLength: expected.length,
    firstDifference: index,
    actualPreview: index < 0 ? "" : actual.slice(windowStart, windowEnd),
    expectedPreview: index < 0 ? "" : expected.slice(windowStart, windowEnd)
  });
}

function normalizeNewlines(value) {
  return value.replace(/\r\n?/gu, "\n");
}

function verifyGeneratedCatalogs() {
  const stale = generatedCatalogFiles().map((file) => {
    const actual = fs.readFileSync(file.path, "utf8");
    const normalizedActual = normalizeNewlines(actual);
    const normalizedExpected = normalizeNewlines(file.content);
    return normalizedActual === normalizedExpected ? null : Object.freeze({
      file: path.relative(root, file.path).replaceAll("\\", "/"),
      difference: summarizeDifference(normalizedActual, normalizedExpected)
    });
  }).filter(Boolean);
  if (stale.length > 0) throw new Error(`capability catalogs are stale; run node scripts/generate-capability-catalogs.js\n${JSON.stringify(stale, null, 2)}`);
  return true;
}

if (require.main === module) {
  try {
    if (process.argv.includes("--check")) verifyGeneratedCatalogs();
    else writeGeneratedCatalogs();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "capability catalog generation failed"}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  generatedCatalogFiles,
  sourceCatalogFromManifests,
  verifyGeneratedCatalogs,
  writeGeneratedCatalogs
};
