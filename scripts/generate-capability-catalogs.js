#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const sourceFile = path.join(root, "packages", "capability-manifests", "capability-module-sources.json");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/u, ""));
}

function assertName(value, label) {
  if (typeof value !== "string" || !/^[A-Za-z][A-Za-z0-9_]*$/u.test(value)) throw new TypeError(`${label} is invalid`);
  return value;
}

function assertCapability(value, label) {
  if (typeof value !== "string" || !/^[a-z][a-z0-9-]{2,63}$/u.test(value)) throw new TypeError(`${label} is invalid`);
  return value;
}

function assertPackageName(value, label) {
  if (typeof value !== "string" || !/^@common-tools\/[a-z][a-z0-9-]*$/u.test(value)) throw new TypeError(`${label} is invalid`);
  return value;
}

function assertRequirePath(value, label) {
  if (typeof value !== "string" || !/^\.\.\/[a-z][a-z0-9-]*$/u.test(value)) throw new TypeError(`${label} is invalid`);
  return value;
}

function assertSourceEntry(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new TypeError(`${label} is invalid`);
  const keys = Object.keys(value).sort().join(",");
  if (keys !== "capability,exportName,packageName,requirePath") throw new TypeError(`${label} keys are invalid`);
  return Object.freeze({
    capability: assertCapability(value.capability, `${label}.capability`),
    packageName: assertPackageName(value.packageName, `${label}.packageName`),
    requirePath: assertRequirePath(value.requirePath, `${label}.requirePath`),
    exportName: assertName(value.exportName, `${label}.exportName`)
  });
}

function assertSourceEntries(value, label) {
  if (!Array.isArray(value)) throw new TypeError(`${label} is invalid`);
  const entries = value.map((entry, index) => assertSourceEntry(entry, `${label}[${index}]`));
  for (const key of ["capability", "packageName", "requirePath"]) {
    const seen = new Set();
    for (const entry of entries) {
      if (seen.has(entry[key])) throw new TypeError(`${label} contains duplicate ${key}: ${entry[key]}`);
      seen.add(entry[key]);
    }
  }
  return Object.freeze(entries);
}

function validateSourceCatalog(value) {
  if (!value || typeof value !== "object" || Array.isArray(value) || value.version !== 1) throw new TypeError("capability module sources are invalid");
  if (Object.keys(value).sort().join(",") !== "direct,local,version") throw new TypeError("capability module sources keys are invalid");
  return Object.freeze({
    version: 1,
    local: assertSourceEntries(value.local, "local capability module sources"),
    direct: assertSourceEntries(value.direct, "direct capability module sources")
  });
}

function variableNameFor(entry) {
  return `${entry.capability.replaceAll("-", "_").toUpperCase()}_${entry.exportName}`;
}

function renderLocalCatalog(sources) {
  const imports = sources.map((entry) => `const { ${entry.exportName}: ${variableNameFor(entry)} } = require("${entry.requirePath}");`).join("\n");
  const records = sources.map((entry) => `  Object.freeze({ packageName: "${entry.packageName}", module: ${variableNameFor(entry)} })`).join(",\n");
  return `"use strict";

// Generated by scripts/generate-capability-catalogs.js. Do not edit by hand.
${imports}

const LOCAL_CAPABILITY_CATALOG = Object.freeze([
${records}
]);

function loadLocalCapabilityModules() {
  return Object.freeze(LOCAL_CAPABILITY_CATALOG.map((entry) => entry.module));
}

module.exports = {
  LOCAL_CAPABILITY_CATALOG,
  loadLocalCapabilityModules
};
`;
}

function renderDirectCatalog(sources) {
  const imports = sources.map((entry) => `const { ${entry.exportName}: ${variableNameFor(entry)} } = require("${entry.requirePath}");`).join("\n");
  const modules = sources.map((entry) => `  ${variableNameFor(entry)}`).join(",\n");
  return `"use strict";

// Generated by scripts/generate-capability-catalogs.js. Do not edit by hand.
${imports}

const DIRECT_CAPABILITY_CATALOG = Object.freeze([
${modules}
]);

function directCapabilityModules() {
  return Object.freeze([...DIRECT_CAPABILITY_CATALOG]);
}

function mergeDirectToolMap(label, pick) {
  const merged = {};
  for (const module of DIRECT_CAPABILITY_CATALOG) {
    const entries = pick(module);
    if (!entries || typeof entries !== "object" || Array.isArray(entries)) throw new Error(\`direct capability \${label} map is invalid\`);
    for (const [name, value] of Object.entries(entries)) {
      if (Object.prototype.hasOwnProperty.call(merged, name)) throw new Error(\`duplicate direct capability \${label}: \${name}\`);
      merged[name] = value;
    }
  }
  return Object.freeze(merged);
}

function directToolContracts() {
  const seen = new Set();
  const contracts = [];
  for (const module of DIRECT_CAPABILITY_CATALOG) {
    const tools = module.directToolContracts || [];
    if (!Array.isArray(tools)) throw new Error("direct capability tool contracts are invalid");
    for (const tool of tools) {
      if (!tool || typeof tool !== "object" || typeof tool.name !== "string") throw new Error("direct capability tool contract is invalid");
      if (seen.has(tool.name)) throw new Error(\`duplicate direct capability contract: \${tool.name}\`);
      seen.add(tool.name);
      contracts.push(tool);
    }
  }
  return Object.freeze(contracts);
}

function directToolArguments() {
  return mergeDirectToolMap("argument", (module) => module.directToolArguments || {});
}

function directToolMethods() {
  return mergeDirectToolMap("method", (module) => module.directToolMethods || {});
}

module.exports = {
  DIRECT_CAPABILITY_CATALOG,
  directCapabilityModules,
  directToolArguments,
  directToolContracts,
  directToolMethods,
  mergeDirectToolMap
};
`;
}

function generatedCatalogFiles(catalog = validateSourceCatalog(readJson(sourceFile))) {
  return Object.freeze([
    Object.freeze({
      path: path.join(root, "packages", "capability-registry", "local-capability-catalog.js"),
      content: renderLocalCatalog(catalog.local)
    }),
    Object.freeze({
      path: path.join(root, "packages", "remote-mcp-server", "direct-capability-catalog.js"),
      content: renderDirectCatalog(catalog.direct)
    })
  ]);
}

function writeGeneratedCatalogs() {
  for (const file of generatedCatalogFiles()) fs.writeFileSync(file.path, file.content);
}

function verifyGeneratedCatalogs() {
  const stale = generatedCatalogFiles().filter((file) => fs.readFileSync(file.path, "utf8") !== file.content).map((file) => path.relative(root, file.path).replaceAll("\\", "/"));
  if (stale.length > 0) throw new Error(`capability catalogs are stale; run node scripts/generate-capability-catalogs.js\n- ${stale.join("\n- ")}`);
  return true;
}

if (require.main === module) {
  try {
    if (process.argv.includes("--check")) verifyGeneratedCatalogs();
    else writeGeneratedCatalogs();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "capability catalog generation failed"}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  generatedCatalogFiles,
  validateSourceCatalog,
  verifyGeneratedCatalogs,
  writeGeneratedCatalogs
};
